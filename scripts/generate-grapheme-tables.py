#!/usr/bin/env python3
"""Generate Unicode 18 grapheme properties from pinned, licensed UCD inputs."""

import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "vendor/alacritty_terminal-0.26.0/tests/unicode18"
OUTPUT = ROOT / "vendor/alacritty_terminal-0.26.0/src/term/grapheme_tables.rs"
GCB = {
    "CR": "Cr",
    "LF": "Lf",
    "Control": "Control",
    "Extend": "Extend",
    "ZWJ": "Zwj",
    "Regional_Indicator": "RegionalIndicator",
    "Prepend": "Prepend",
    "SpacingMark": "SpacingMark",
    "L": "L",
    "V": "V",
    "T": "T",
    "LV": "Lv",
    "LVT": "Lvt",
}


def records(name):
    for line in (DATA / name).read_text(encoding="utf-8").splitlines():
        body = line.split("#", 1)[0].strip()
        if not body:
            continue
        fields = [part.strip() for part in body.split(";")]
        bounds = fields[0].split("..")
        yield int(bounds[0], 16), int(bounds[-1], 16), fields[1:]


def table(name, kind, values):
    values.sort()
    previous = -1
    rows = []
    for start, end, value in values:
        if not previous < start <= end <= 0x10FFFF:
            raise ValueError(f"invalid or overlapping {name} range")
        previous = end
        suffix = f", {value}" if value else ""
        rows.append(f"    (0x{start:X}, 0x{end:X}{suffix}),")
    return f"pub(super) const {name}: &[{kind}] = &[\n" + "\n".join(rows) + "\n];\n"


def generate():
    manifest = json.loads((DATA / "sources.json").read_text(encoding="utf-8"))
    if manifest["unicode_version"] != "18.0.0":
        raise ValueError("Unicode version must stay explicit")
    for source in manifest["sources"]:
        if (
            hashlib.sha256((DATA / source["file"]).read_bytes()).hexdigest()
            != source["sha256"]
        ):
            raise ValueError("pinned input changed: " + source["file"])
    gcb = [
        (a, b, "Gcb::" + GCB[p[0]]) for a, b, p in records("GraphemeBreakProperty.txt")
    ]
    ep = [
        (a, b, "")
        for a, b, p in records("emoji-data.txt")
        if p[0] == "Extended_Pictographic"
    ]
    presentation = [
        (a, b, "")
        for a, b, p in records("emoji-data.txt")
        if p[0] == "Emoji_Presentation"
    ]
    incb = [
        (a, b, "InCb::" + p[1])
        for a, b, p in records("DerivedCoreProperties.txt")
        if p[0] == "InCB"
    ]
    result = "// Unicode 18.0.0. Generated by scripts/generate-grapheme-tables.py.\n"
    result += "// Source data and Unicode-3.0 license: ../../tests/unicode18/.\n"
    result += "use super::{Gcb, InCb};\n\n"
    result += table("GCB", "(u32, u32, Gcb)", gcb) + "\n"
    result += table("EXTENDED_PICTOGRAPHIC", "(u32, u32)", ep) + "\n"
    result += table("EMOJI_PRESENTATION", "(u32, u32)", presentation) + "\n"
    result += table("INCB", "(u32, u32, InCb)", incb)
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != output:
            raise SystemExit(
                "grapheme tables differ; run scripts/generate-grapheme-tables.py"
            )
    else:
        OUTPUT.write_text(output, encoding="utf-8", newline="\n")
    print("Unicode 18 grapheme tables: PASS")


if __name__ == "__main__":
    main()
