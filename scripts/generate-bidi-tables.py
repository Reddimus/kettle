#!/usr/bin/env python3
"""Generate Unicode 16 bidi display tables (mirroring, Arabic joining and
presentation forms) from pinned, licensed UCD inputs."""

import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "crates/kettle-core/data/ucd-16.0.0"
OUTPUT = ROOT / "crates/kettle-core/src/bidi_tables.rs"
# The Joining_Type values the display needs; U (non-joining) is the default.
JOINING = {"R": "Right", "L": "Left", "D": "Dual", "C": "Causing", "T": "Transparent"}
FORM_SLOTS = {"<isolated>": 0, "<final>": 1, "<initial>": 2, "<medial>": 3}


def lines(name):
    for line in (DATA / name).read_text(encoding="utf-8").splitlines():
        body = line.split("#", 1)[0].strip()
        if body:
            yield [part.strip() for part in body.split(";")]


def mirrors():
    pairs = sorted((int(a, 16), int(b, 16)) for a, b in lines("BidiMirroring.txt"))
    if len({a for a, _ in pairs}) != len(pairs):
        raise ValueError("duplicate mirroring source")
    return pairs


def joining():
    rows = []
    for fields in lines("ArabicShaping.txt"):
        kind = fields[2]
        if kind == "U":
            continue
        code = int(fields[0], 16)
        if rows and rows[-1][1] == code - 1 and rows[-1][2] == kind:
            rows[-1][1] = code
        else:
            rows.append([code, code, kind])
    return rows


def forms():
    table = {}
    for fields in lines("UnicodeData-arabic-forms.txt"):
        code, decomposition = int(fields[0], 16), fields[5]
        parts = decomposition.split()
        # Single letters only: the lam-alef ligatures decompose to two
        # characters and stay two cells, as in VTE and Konsole.
        if len(parts) != 2 or parts[0] not in FORM_SLOTS:
            continue
        base = int(parts[1], 16)
        slots = table.setdefault(base, [None, None, None, None])
        if slots[FORM_SLOTS[parts[0]]] is None:
            slots[FORM_SLOTS[parts[0]]] = code
    return sorted(table.items())


def char(code):
    return f"'\\u{{{code:X}}}'"


def generate():
    manifest = json.loads((DATA / "sources.json").read_text(encoding="utf-8"))
    if manifest["unicode_version"] != "16.0.0":
        raise ValueError("Unicode version must stay explicit")
    for source in manifest["sources"]:
        if hashlib.sha256((DATA / source["file"]).read_bytes()).hexdigest() != source["sha256"]:
            raise ValueError("pinned input changed: " + source["file"])
    out = "// Unicode 16.0.0. Generated by scripts/generate-bidi-tables.py.\n"
    out += "// Source data and Unicode-3.0 license: ../data/ucd-16.0.0/.\n"
    out += "use super::Joining;\n\n"
    out += "pub(super) const UCD_VERSION: (u64, u64, u64) = (16, 0, 0);\n\n"
    pairs = mirrors()
    out += f"pub(super) const MIRRORS: &[(char, char); {len(pairs)}] = &[\n"
    out += "".join(f"    ({char(a)}, {char(b)}),\n" for a, b in pairs) + "];\n\n"
    out += "pub(super) const JOINING: &[(u32, u32, Joining)] = &[\n"
    out += "".join(
        f"    (0x{a:X}, 0x{b:X}, Joining::{JOINING[kind]}),\n" for a, b, kind in joining()
    ) + "];\n\n"
    out += "/// Isolated, final, initial and medial presentation forms.\n"
    out += "pub(super) const FORMS: &[(char, [Option<char>; 4])] = &[\n"
    for base, slots in forms():
        cells = ", ".join("None" if s is None else f"Some({char(s)})" for s in slots)
        out += f"    ({char(base)}, [{cells}]),\n"
    return out + "];\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != output:
            raise SystemExit("bidi tables differ; run scripts/generate-bidi-tables.py")
    else:
        OUTPUT.write_text(output, encoding="utf-8", newline="\n")
    print("Unicode 16 bidi tables: PASS")


if __name__ == "__main__":
    main()
